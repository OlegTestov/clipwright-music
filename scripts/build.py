"""Build the library: copy the picked tracks into dist/, measure them and write dist/manifest.json.

Usage: python build.py picks.json
picks.json: {"<mood>": ["<file in data/pool or data/lyria>", ...], ...}
Per track the manifest holds what the app and agents need to pick and cut to it: mood, BPM, length, beat times,
loudness and true peak (the app sets the gain), licence and provenance, SHA-256 of the file as served.
A track must have passed the vocal-stem check (scripts/vocals.py -> data/vocals.json, rule in voice_rule.py);
the build stops on a track that was not checked or has a voice.
"""

import hashlib
import json
import re
import shutil
import subprocess
import sys
from pathlib import Path

import librosa
import numpy as np

sys.path.insert(0, str(Path(__file__).resolve().parent))
from voice_rule import has_voice, voiced_at  # noqa: E402

ROOT = Path(__file__).resolve().parent.parent
DIST = ROOT / "dist"
FFMPEG = "/opt/homebrew/bin/ffmpeg"
LYRIA_LICENCE = "CC0-1.0"
LYRIA_NOTE = "Generated by the maintainer with Google Lyria 3.5 (carries Google's inaudible SynthID watermark); dedicated to the public domain under CC0 to the extent the maintainer holds any rights."


def loudness(path: Path) -> tuple[float, float]:
    r = subprocess.run([FFMPEG, "-nostats", "-i", str(path), "-af", "ebur128=peak=true", "-f", "null", "-"], capture_output=True, text=True)
    tail = r.stderr[r.stderr.rfind("Summary:"):]
    lufs = float(re.search(r"I:\s+(-?[\d.]+) LUFS", tail).group(1))
    peak = float(re.search(r"Peak:\s+(-?[\d.]+) dBFS", tail).group(1))
    return lufs, peak


def beats(path: Path) -> tuple[float, list[float]]:
    y, sr = librosa.load(path, sr=22050, mono=True)
    tempo, frames = librosa.beat.beat_track(y=y, sr=sr)
    times = librosa.frames_to_time(frames, sr=sr)
    return float(np.atleast_1d(tempo)[0]), [round(float(t), 3) for t in times]


def main() -> None:
    picks = json.loads(Path(sys.argv[1]).read_text())
    pool = {e["id"] + ".mp3": e for e in json.loads((ROOT / "data" / "pool.json").read_text())}
    ratings = {}
    for f in ("ratings-pool.json", "ratings-pool-fma.json", "ratings.json"):
        p = ROOT / "data" / f
        if p.exists():
            ratings.update(json.loads(p.read_text()))
    (DIST / "tracks").mkdir(parents=True, exist_ok=True)
    vocals = json.loads((ROOT / "data" / "vocals.json").read_text())
    tracks = []
    for mood, files in picks.items():
        for name in files:
            src = ROOT / "data" / ("pool" if name in pool else "lyria") / name
            entry = pool.get(name)
            tid = entry["id"] if entry else f"lyria-{Path(name).stem}"
            dest = DIST / "tracks" / f"{tid}.mp3"
            check = vocals.get(f"{tid}.mp3") or vocals.get(name)
            if check is None or has_voice(check):
                sys.exit(f"{name}: " + ("not voice-checked" if check is None else f"voice at {voiced_at(check)} s"))
            shutil.copyfile(src, dest)
            lufs, peak = loudness(dest)
            bpm, beat_times = beats(dest)
            rating = ratings.get(name, {}).get("model", {})
            tracks.append({
                "id": tid,
                "title": entry["title"] if entry else Path(name).stem.replace("-", " ").title(),
                "mood": mood,
                "bpm": round(bpm, 1),
                "duration": round(float(librosa.get_duration(path=dest)), 2),
                "beats": beat_times,
                "lufs": lufs,
                "true_peak_db": peak,
                "energy": rating.get("energy"),
                "best_for": rating.get("best_for"),
                "author": entry["author"] if entry else "Clipwright maintainer (AI-generated)",
                "licence": entry["licence"] if entry else LYRIA_LICENCE,
                "source": entry["source_page"] if entry else None,
                "provenance": entry["provenance"] if entry else LYRIA_NOTE,
                "ai_generated": entry is None,
                "file": f"{tid}.mp3",
                "size": dest.stat().st_size,
                "sha256": hashlib.sha256(dest.read_bytes()).hexdigest(),
            })
            print(mood, tid, round(bpm), lufs, peak, flush=True)
    manifest = {"version": 1, "tracks": tracks}
    (DIST / "manifest.json").write_text(json.dumps(manifest, indent=1, ensure_ascii=False))
    print("tracks:", len(tracks))


if __name__ == "__main__":
    main()
